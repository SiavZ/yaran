#!/usr/bin/env node
/**
 * Exports the kit's dark tokens as native colors for the phone app's two projects.
 *
 * The phone shell is dark-only like the web, and its native chrome (splash, system
 * bars, the lock screen) must match the WebView's pixels. This reads the `.dark` block
 * of `src/tokens.css`, converts each named token from `oklch()` to sRGB, and writes an
 * Android color resource file and an iOS asset catalog. Run it after changing a token;
 * `--check` (part of `npm test`) fails when the committed files have drifted.
 *
 * - Android: `mobile/android/app/src/main/res/values/yaran_colors.xml`, `@color/yaran_<token>`.
 * - iOS: `mobile/ios/App/App/Colors.xcassets/Yaran<Token>.colorset/Contents.json`.
 * - A token with alpha (`oklch(1 0 0 / 10%)`) keeps it: `#AARRGGBB` on Android, the
 *   colorset's alpha component on iOS.
 *
 * <module-headers:begin>
 * Uses: none
 * External: node:fs, node:path, node:url
 *
 * Used by: entry point (CLI: npm run colors / npm test (--check) in packages/ui-kit)
 * scripts/export-native-colors.mjs
 * └── scripts/export-native-colors.test.mjs
 * <module-headers:end>
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(fileURLToPath(new URL(".", import.meta.url)), "../../..");
const TOKENS = join(REPO, "packages/ui-kit/src/tokens.css");
const ANDROID = join(REPO, "mobile/android/app/src/main/res/values/yaran_colors.xml");
const CATALOG = join(REPO, "mobile/ios/App/App/Colors.xcassets");

/** The tokens native chrome needs; the names are the Phase 14 contract. */
export const TOKEN_NAMES = [
  "background", "foreground", "card", "card-foreground", "primary", "primary-foreground",
  "muted", "muted-foreground", "border", "destructive",
];

/**
 * The custom properties declared in the `.dark { ... }` block.
 * @param {string} css
 * @returns {Map<string, string>}
 */
export function darkTokens(css) {
  const block = /(?:^|\n)\.dark\s*\{([^}]*)\}/.exec(css.replace(/\/\*[\s\S]*?\*\//g, ""));
  if (!block) throw new Error("tokens.css has no .dark block");
  const out = new Map();
  for (const m of block[1].matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) out.set(m[1], m[2].trim());
  return out;
}

/**
 * Converts a CSS `oklch(L C h [/ A])` to sRGB through OKLab, the way a browser paints it
 * today: an out-of-gamut channel is clipped to [0, 1] (CSS Color 4's chroma-reducing
 * gamut map is not what shipping engines do for opaque fills).
 * @param {string} value
 * @returns {{ r: number, g: number, b: number, a: number }} 8-bit channels, alpha 0..1
 */
export function oklchToRgb(value) {
  const m = /^oklch\(\s*([\d.]+)(%?)\s+([\d.]+)\s+([\d.]+)(?:deg)?\s*(?:\/\s*([\d.]+)(%?))?\s*\)$/.exec(value);
  if (!m) throw new Error(`unsupported color "${value}" (expected oklch(L C h [/ A]))`);
  const L = Number(m[1]) / (m[2] ? 100 : 1);
  const C = Number(m[3]);
  const h = (Number(m[4]) * Math.PI) / 180;
  const a = m[5] === undefined ? 1 : Number(m[5]) / (m[6] ? 100 : 1);
  const A = C * Math.cos(h);
  const B = C * Math.sin(h);
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const mm = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * mm + 1.707614701 * s,
  ];
  const [r, g, b] = lin.map((x) => {
    const v = Math.min(1, Math.max(0, x));
    const enc = v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
    return Math.round(enc * 255);
  });
  return { r, g, b, a };
}

const hex2 = (/** @type {number} */ n) => n.toString(16).toUpperCase().padStart(2, "0");

/** @param {{ r: number, g: number, b: number, a: number }} c */
export function androidHex(c) {
  const alpha = c.a < 1 ? hex2(Math.round(c.a * 255)) : "";
  return `#${alpha}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}`;
}

/** @param {string} token */
const camel = (token) => token.replace(/(^|-)(\w)/g, (_, _d, ch) => ch.toUpperCase());

/** @returns {Map<string, string>} absolute path -> expected contents */
export function expectedFiles(css = readFileSync(TOKENS, "utf8")) {
  const tokens = darkTokens(css);
  const colors = TOKEN_NAMES.map((name) => {
    const value = tokens.get(name);
    if (value === undefined) throw new Error(`tokens.css .dark is missing --${name}`);
    return { name, rgb: oklchToRgb(value) };
  });
  const files = new Map();
  const xml = [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- @generated by packages/ui-kit/scripts/export-native-colors.mjs from tokens.css (.dark). Do not edit. -->",
    "<resources>",
    ...colors.map((c) => `    <color name="yaran_${c.name.replace(/-/g, "_")}">${androidHex(c.rgb)}</color>`),
    "</resources>",
    "",
  ];
  files.set(ANDROID, xml.join("\n"));
  const info = { author: "xcode", version: 1 };
  files.set(join(CATALOG, "Contents.json"), json({ info }));
  for (const { name, rgb } of colors) {
    const components = { alpha: rgb.a.toFixed(3), blue: `0x${hex2(rgb.b)}`, green: `0x${hex2(rgb.g)}`, red: `0x${hex2(rgb.r)}` };
    const color = { color: { "color-space": "srgb", components }, idiom: "universal" };
    files.set(join(CATALOG, `Yaran${camel(name)}.colorset`, "Contents.json"), json({ colors: [color], info }));
  }
  return files;
}

/** @param {unknown} v */
const json = (v) => `${JSON.stringify(v, null, 2)}\n`;

/** Colorsets this script owns that no longer correspond to a token. */
function staleColorsets(/** @type {Map<string, string>} */ files) {
  if (!existsSync(CATALOG)) return [];
  return readdirSync(CATALOG)
    .filter((d) => /^Yaran\w+\.colorset$/.test(d))
    .map((d) => join(CATALOG, d))
    .filter((dir) => !files.has(join(dir, "Contents.json")));
}

function main() {
  const check = process.argv.includes("--check");
  const files = expectedFiles();
  const drift = [];
  for (const [path, want] of files) {
    const have = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (have === want) continue;
    drift.push(relative(REPO, path));
    if (!check) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, want);
    }
  }
  for (const dir of staleColorsets(files)) {
    drift.push(relative(REPO, dir));
    if (!check) rmSync(dir, { recursive: true });
  }
  if (check && drift.length > 0) {
    console.error(`export-native-colors: out of date: ${drift.join(", ")}\nrun: node packages/ui-kit/scripts/export-native-colors.mjs`);
    process.exit(1);
  }
  console.log(`export-native-colors: ${check ? "up to date" : `${drift.length} file(s) written`}`);
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main();

/**
 * File enumeration rules: language detection (extension and shebang), the generated and
 * vendored exemptions, line counting, and the scope glob matcher.
 *
 * <module-headers:begin>
 * Uses:
 * test/files.test.mjs
 * ├── src/config.mjs
 * └── src/files.mjs
 * External: node:assert/strict, node:test
 *
 * Used by: entry point (node --test, via npm test in tools/module-headers)
 * <module-headers:end>
 */

import { test } from "node:test";
import assert from "node:assert/strict";
import { detectLang, isLineCounted, isExempt, countLines } from "../src/files.mjs";
import { globToRegExp, compileScope, validateScope } from "../src/config.mjs";

test("languages by extension and by shebang", () => {
  assert.equal(detectLang("a/b.rs", ""), "rust");
  assert.equal(detectLang("a/b.tsx", ""), "ts");
  assert.equal(detectLang("a/b.mjs", ""), "ts");
  assert.equal(detectLang("A.kts", ""), "kotlin");
  assert.equal(detectLang("x.swift", ""), "swift");
  assert.equal(detectLang("t.bats", ""), "shell");
  assert.equal(detectLang("bin/tool", "#!/usr/bin/env bash\n"), "shell");
  assert.equal(detectLang("bin/tool", "#!/bin/sh\n"), "shell");
  assert.equal(detectLang("bin/tool", "#!/usr/bin/env -S bash -eu\n"), "shell");
  assert.equal(detectLang("bin/tool", "#!/usr/bin/env node\n"), undefined);
  assert.equal(detectLang("README", "hello\n"), undefined);
});

test("what the line gate counts", () => {
  assert.equal(isLineCounted(".github/workflows/gates.yml", ""), true);
  assert.equal(isLineCounted("bin/tool", "#!/usr/bin/env python3\n"), true);
  assert.equal(isLineCounted("docs/x.md", ""), false);
  assert.equal(isLineCounted("package-lock.json", ""), false);
  assert.equal(isLineCounted("LICENSE", "MIT\n"), false);
});

test("@generated in the first five lines exempts; vendored only exempts .d.ts", () => {
  assert.equal(isExempt("x.ts", "// line\n// @generated by gen-types\n"), true);
  assert.equal(isExempt("x.ts", "1\n2\n3\n4\n5\n// @generated\n"), false);
  assert.equal(isExempt("v.d.ts", "// vendored from upstream\n"), true);
  assert.equal(isExempt("v.ts", "// vendored from upstream\n"), false);
});

test("line counting matches an editor", () => {
  assert.equal(countLines(""), 0);
  assert.equal(countLines("a"), 1);
  assert.equal(countLines("a\n"), 1);
  assert.equal(countLines("a\nb"), 2);
  assert.equal(countLines("a\n\n"), 2);
});

test("glob matching", () => {
  assert.ok(globToRegExp("cloud/**").test("cloud/worker/src/x.ts"));
  assert.ok(globToRegExp("**/fixtures/**").test("cloud/protocol/fixtures/a.json"));
  assert.ok(globToRegExp("**/fixtures/**").test("fixtures/a.json"));
  assert.ok(globToRegExp("crates/yaran-web/src/cloud_*.rs").test("crates/yaran-web/src/cloud_mode.rs"));
  assert.ok(!globToRegExp("crates/yaran-web/src/cloud_*.rs").test("crates/yaran-web/src/sub/cloud_mode.rs"));
  assert.ok(globToRegExp("test/*.test.{mjs,ts}").test("test/a.test.ts"));
  assert.ok(!globToRegExp("cloud/**").test("cloudy/x.ts"));
});

test("scope: roots plus optIn minus exclude, entry points by glob", () => {
  const s = compileScope(validateScope({ roots: ["cloud/**"], optIn: ["crates/x.rs"], exclude: ["**/generated/**"], entryPoints: { "cloud/**/*.test.ts": "vitest" } }));
  assert.ok(s.inScope("cloud/a.ts"));
  assert.ok(s.inScope("crates/x.rs"));
  assert.ok(!s.inScope("cloud/src/generated/types.ts"));
  assert.ok(!s.inScope("crates/y.rs"));
  assert.equal(s.entryPoint("cloud/worker/test/a.test.ts"), "vitest");
  assert.throws(() => validateScope({ roots: [], entryPoints: { a: "" } }), /launch description/);
  assert.throws(() => validateScope({ rots: [] }), /unknown key/);
});

#!/usr/bin/env node
/**
 * Writes the iOS native license list from the Swift package manifests, offline.
 *
 * Collects every remote `.package(url:…)` dependency (with its pinned version) from the app's
 * `CapApp-SPM/Package.swift` and every local plugin's `Package.swift`, and names its license
 * from the table below. An unknown dependency fails the run, so adding a Swift dependency
 * forces a reviewed license entry. Used by `licenses.sh` in place of LicensePlist, which
 * needs Xcode's resolved checkouts and GitHub API calls.
 *
 * - Pure file reads; no network.
 *
 * <module-headers:begin>
 * Uses: none
 * External: node:fs, node:path, node:url
 *
 * Used by:
 * mobile/scripts/ios-licenses.mjs
 * └── mobile/scripts/licenses.test.mjs
 * <module-headers:end>
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const MOBILE = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Reviewed licenses of remote Swift packages, keyed by repository URL. */
export const KNOWN_LICENSES = {
  'https://github.com/ionic-team/capacitor-swift-pm.git': { name: 'Capacitor', license: 'MIT' },
};

const PACKAGE_RE = /\.package\(\s*url:\s*"([^"]+)"\s*,\s*(?:exact|from):\s*"([^"]+)"/g;

/** Remote dependencies declared in one manifest's text. */
export function remoteDependencies(manifest) {
  return [...manifest.matchAll(PACKAGE_RE)].map((m) => ({ url: m[1], version: m[2] }));
}

export function manifests(root = MOBILE) {
  const plugins = join(root, 'plugins');
  const fromPlugins = existsSync(plugins)
    ? readdirSync(plugins).map((d) => join(plugins, d, 'Package.swift')).filter(existsSync)
    : [];
  return [join(root, 'ios', 'App', 'CapApp-SPM', 'Package.swift'), ...fromPlugins].filter(existsSync);
}

const newer = (a, b) => a.localeCompare(b, 'en', { numeric: true }) > 0;

/** Builds the list; throws on a dependency with no reviewed license. */
export function iosLicenseList(paths = manifests()) {
  const entries = new Map();
  for (const path of paths) {
    for (const dep of remoteDependencies(readFileSync(path, 'utf8'))) {
      const known = KNOWN_LICENSES[dep.url];
      if (!known) throw new Error(`no reviewed license for ${dep.url} (in ${path}); add it to KNOWN_LICENSES`);
      const version = dep.version.replace(/^v/, '');
      const prev = entries.get(known.name);
      // `from:` floors and `exact:` pins can differ across manifests; the highest version wins.
      if (!prev || newer(version, prev.version)) entries.set(known.name, { name: known.name, version, license: known.license });
    }
  }
  return { generated: '@generated by mobile/scripts/licenses.sh; do not edit', entries: [...entries.values()].sort((a, b) => a.name.localeCompare(b.name)) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = process.argv[2];
  if (!out) {
    console.error('usage: ios-licenses.mjs <out.json>');
    process.exit(2);
  }
  writeFileSync(out, `${JSON.stringify(iosLicenseList(), null, 2)}\n`);
}

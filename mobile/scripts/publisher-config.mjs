#!/usr/bin/env node
/**
 * Publisher build-config loader: one source of publisher values for both native projects.
 *
 * Copies `publisher_domain` from the repo-root `publisher.json` (Phase 18's one home for the
 * publisher domain) into `mobile/publisher.properties`, then renders the iOS
 * `mobile/ios/App/Config/Publisher.xcconfig` and `E2E.xcconfig` from the properties file.
 * Android reads the properties file directly in `app/build.gradle.kts`.
 *
 * - `--check` writes nothing and exits 1 on drift in either step (Phase 18 runs it in CI).
 * - A missing publisher.json or its `<publisher-domain>` placeholder means an empty domain,
 *   which is a development build (D8, D16).
 * - `e2e.*` keys reach only E2E.xcconfig (Phase 19 hook H6); release configurations never see them.
 *
 * <module-headers:begin>
 * Uses: none
 * External: node:fs, node:path, node:url
 *
 * Used by:
 * mobile/scripts/publisher-config.mjs
 * └── mobile/scripts/publisher-config.test.mjs
 * <module-headers:end>
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const MOBILE = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PATHS = {
  publisherJson: join(MOBILE, '..', 'publisher.json'),
  properties: join(MOBILE, 'publisher.properties'),
  publisherXcconfig: join(MOBILE, 'ios', 'App', 'Config', 'Publisher.xcconfig'),
  e2eXcconfig: join(MOBILE, 'ios', 'App', 'Config', 'E2E.xcconfig'),
};
const PLACEHOLDER = '<publisher-domain>';
const HOST_RE = /^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;

/** The publisher domain publisher.json names, or '' for none/placeholder; throws on a bad value. */
export function domainFromPublisherJson(text) {
  if (text === null) return '';
  const value = JSON.parse(text).publisher_domain ?? '';
  if (value === '' || value === PLACEHOLDER) return '';
  if (typeof value !== 'string' || !HOST_RE.test(value)) {
    throw new Error(`publisher.json publisher_domain must be a lowercase host name, got ${JSON.stringify(value)}`);
  }
  return value;
}

/** Parses `key=value` lines (comments and blanks skipped); duplicate keys are an error. */
export function parseProperties(text) {
  const out = new Map();
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (line === '' || line.startsWith('#') || line.startsWith('!')) continue;
    const eq = line.indexOf('=');
    if (eq < 0) throw new Error(`publisher.properties: no "=" in line ${JSON.stringify(line)}`);
    const key = line.slice(0, eq).trim();
    if (out.has(key)) throw new Error(`publisher.properties: duplicate key ${key}`);
    out.set(key, line.slice(eq + 1).trim());
  }
  return out;
}

/** Rewrites the `publisherDomain=` line in place, keeping every comment. */
export function withDomain(propertiesText, domain) {
  if (!/^publisherDomain=.*$/m.test(propertiesText)) throw new Error('publisher.properties has no publisherDomain key');
  return propertiesText.replace(/^publisherDomain=.*$/m, `publisherDomain=${domain}`);
}

// `//` starts a comment in an xcconfig, so URLs are written with the documented `/$()/` escape.
const xc = (value) => value.replaceAll('//', '/$()/');

const HEADER = (source) =>
  `// @generated by mobile/scripts/publisher-config.mjs from ${source}; do not edit.\n` +
  '// Run `node mobile/scripts/publisher-config.mjs` after changing mobile/publisher.properties.\n';

/** Renders both xcconfig files from the parsed properties. */
export function renderXcconfigs(props) {
  const get = (k) => props.get(k) ?? '';
  const domain = get('publisherDomain');
  const publisher =
    HEADER('mobile/publisher.properties') +
    `APP_ID = ${get('appId')}\n` +
    `PRODUCT_BUNDLE_IDENTIFIER = $(APP_ID)\n` +
    `APPLE_TEAM_ID = ${get('appleTeamId')}\n` +
    `DEVELOPMENT_TEAM = $(APPLE_TEAM_ID)\n` +
    `PUBLISHER_DOMAIN = ${domain}\n` +
    `RELAY_URL = ${xc(get('relayUrl'))}\n` +
    `PLAY_PUSH_TRANSPORT = ${get('playPushTransport')}\n` +
    // Associated domains only exist in a build with a publisher domain (D8, T36).
    `CODE_SIGN_ENTITLEMENTS = ${domain === '' ? 'App/App.entitlements' : 'App/App+Publisher.entitlements'}\n`;
  const e2e =
    HEADER('mobile/publisher.properties (e2e.* keys)') +
    '#include "Publisher.xcconfig"\n' +
    `E2E_CONTROL_PLANE_URL = ${xc(get('e2e.controlPlaneUrl'))}\n` +
    `E2E_RELAY_URL = ${xc(get('e2e.relayUrl'))}\n` +
    'SWIFT_ACTIVE_COMPILATION_CONDITIONS = $(inherited) E2E\n';
  return { publisher, e2e };
}

const readOrNull = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : null);

/** Computes every output; returns the list of [path, wanted text] pairs. */
export function plan(paths = PATHS) {
  const domain = domainFromPublisherJson(readOrNull(paths.publisherJson));
  const properties = withDomain(readFileSync(paths.properties, 'utf8'), domain);
  const { publisher, e2e } = renderXcconfigs(parseProperties(properties));
  return [
    [paths.properties, properties],
    [paths.publisherXcconfig, publisher],
    [paths.e2eXcconfig, e2e],
  ];
}

/** Writes (or with check=true compares) every output; returns the drifted paths. */
export function run({ check = false, paths = PATHS } = {}) {
  const drifted = [];
  for (const [path, wanted] of plan(paths)) {
    if (readOrNull(path) === wanted) continue;
    drifted.push(path);
    if (!check) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, wanted);
    }
  }
  return drifted;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  try {
    const drifted = run({ check });
    if (check && drifted.length > 0) {
      console.error(`publisher config drift; run node mobile/scripts/publisher-config.mjs:\n  ${drifted.join('\n  ')}`);
      process.exit(1);
    }
    console.log(check ? 'publisher config: no drift' : `publisher config: wrote ${drifted.length} file(s)`);
  } catch (err) {
    console.error(`publisher config: ${err.message}`);
    process.exit(1);
  }
}

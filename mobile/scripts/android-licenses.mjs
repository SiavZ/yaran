#!/usr/bin/env node
/**
 * Converts an AboutLibraries `exportLibraryDefinitions` JSON into the shell's license list.
 *
 * AboutLibraries writes `{ libraries: [{ uniqueId, artifactVersion, name, licenses: [id] }],
 * licenses: { id: { name, spdxId } } }`; the shell renders `{ name, version, license }`
 * entries, the same shape as the JS and iOS lists. Sorted for stable diffs.
 *
 * - Pure transform; reads one file, writes one file.
 *
 * <module-headers:begin>
 * Uses: none
 * External: node:fs, node:url
 *
 * Used by:
 * mobile/scripts/android-licenses.mjs
 * └── mobile/scripts/licenses.test.mjs
 * <module-headers:end>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function convertAboutLibraries(doc) {
  const licenses = doc.licenses ?? {};
  const entries = (doc.libraries ?? []).map((lib) => ({
    name: lib.uniqueId,
    version: lib.artifactVersion ?? '',
    license:
      (lib.licenses ?? [])
        .map((id) => licenses[id]?.spdxId || licenses[id]?.name || id)
        .join(' AND ') || 'UNKNOWN',
  }));
  entries.sort((a, b) => a.name.localeCompare(b.name));
  return { generated: '@generated by mobile/scripts/licenses.sh; do not edit', entries };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [input, out] = process.argv.slice(2);
  if (!input || !out) {
    console.error('usage: android-licenses.mjs <aboutlibraries.json> <out.json>');
    process.exit(2);
  }
  writeFileSync(out, `${JSON.stringify(convertAboutLibraries(JSON.parse(readFileSync(input, 'utf8'))), null, 2)}\n`);
}

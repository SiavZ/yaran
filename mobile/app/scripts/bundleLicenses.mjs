/**
 * Vite plugin that lists the third-party packages actually bundled into the shell.
 *
 * At `generateBundle` it walks every module id in the build, maps each `node_modules` path to
 * its package, and writes `{ name, version, license }` entries (sorted, first-party
 * `@yaran/*` excluded) to the file named by `YARAN_LICENSES_OUT`. Only what ships is listed,
 * not build tools. `mobile/scripts/licenses.sh` drives it.
 *
 * - Inert unless `YARAN_LICENSES_OUT` is set; a normal build writes nothing.
 *
 * <module-headers:begin>
 * Uses: none
 * External: node:fs, node:path
 *
 * Used by: entry point (Vite plugin loaded by mobile/app/vite.config.ts; switched on by mobile/scripts/licenses.sh)
 * <module-headers:end>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const NM = 'node_modules/';

/** The package directory owning a module id (the innermost node_modules entry), or null. */
export function packageDirOf(id) {
  const clean = id.replace(/^\0/, '').split('?')[0];
  const at = clean.lastIndexOf(NM);
  if (at < 0) return null;
  const parts = clean.slice(at + NM.length).split('/');
  const name = parts[0].startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
  return clean.slice(0, at + NM.length) + name;
}

export function bundleLicenses(outFile = process.env.YARAN_LICENSES_OUT) {
  return {
    name: 'yaran-bundle-licenses',
    apply: 'build',
    generateBundle() {
      if (!outFile) return;
      const entries = new Map();
      for (const id of this.getModuleIds()) {
        const dir = packageDirOf(id);
        if (!dir) continue;
        const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
        if (pkg.name.startsWith('@yaran/')) continue;
        const license = typeof pkg.license === 'string' ? pkg.license : 'SEE LICENSE FILE';
        entries.set(`${pkg.name}@${pkg.version}`, { name: pkg.name, version: pkg.version, license });
      }
      const sorted = [...entries.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
      const doc = { generated: '@generated by mobile/scripts/licenses.sh; do not edit', entries: sorted };
      writeFileSync(outFile, `${JSON.stringify(doc, null, 2)}\n`);
    },
  };
}

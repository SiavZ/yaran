#!/usr/bin/env node
/**
 * Generates `src/generated/types.ts` from the JSON Schemas and the registries.
 *
 * Every `$defs` entry of every `schemas/*.schema.json` becomes a named TypeScript type
 * (via json-schema-to-typescript), and the registries become literal unions
 * (`ErrorCode`, `RefusalCode`, `Capability`, `AuditAction`). `--check` regenerates in
 * memory and fails if the committed file differs, which CI runs as `npm run gen:check`.
 *
 * - Writes one file; never touches schemas.
 *
 * <module-headers:begin>
 * Uses: none
 * External: json-schema-to-typescript, node:fs, node:path, node:url
 *
 * Used by: entry point (CLI: npm run gen / gen:check in cloud/protocol, and cloud-protocol.yml)
 * <module-headers:end>
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemasDir = join(root, "schemas");
const outFile = join(root, "src/generated/types.ts");
const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));

const files = readdirSync(schemasDir).filter((f) => f.endsWith(".schema.json")).sort();
const defs = {};
for (const file of files) {
  for (const name of Object.keys(readJson(join(schemasDir, file)).$defs)) {
    if (defs[name]) throw new Error(`type ${name} is defined twice`);
    defs[name] = { $ref: `${file}#/$defs/${name}` };
  }
}

const body = await compile(
  { title: "YaranProtocolTypes", type: "object", additionalProperties: false, properties: {}, $defs: defs },
  "YaranProtocolTypes",
  {
    cwd: schemasDir,
    bannerComment: "",
    unreachableDefinitions: true,
    additionalProperties: false,
    strictIndexSignatures: true,
    format: true,
    maxItems: -1,
    style: { printWidth: 110 },
  },
);

const union = (name, values) =>
  `export type ${name} =\n${values.map((v) => `  | ${JSON.stringify(v)}`).join("\n")};\n`;
const reg = (f) => readJson(join(root, "registry", f));

const out = [
  "// @generated by scripts/gen-types.mjs from schemas/*.schema.json and registry/*.json. Do not edit.",
  "// Regenerate with `npm run gen`; CI checks it with `npm run gen:check`.",
  "",
  body
    .replace(/export interface YaranProtocolTypes \{\}\n?/, "")
    .trim(),
  "",
  union("ErrorCode", reg("errors.json").codes.map((c) => c.code)),
  union("RefusalCode", reg("refusals.json").refusals.map((r) => r.code)),
  union("Capability", reg("capabilities.json").capabilities),
  union("AuditAction", reg("audit-actions.json").actions),
].join("\n");

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8");
  if (current !== out) {
    console.error("src/generated/types.ts is stale; run `npm run gen`.");
    process.exit(1);
  }
  console.log("src/generated/types.ts is up to date.");
} else {
  writeFileSync(outFile, out);
  console.log(`wrote ${outFile}`);
}
